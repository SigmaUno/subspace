package postgres

import (
	"context"
	"time"

	"github.com/SigmaUno/subspace/internal/insights"
	"github.com/SigmaUno/subspace/internal/store"
)

func init() {
	RegisterSchema(`
CREATE TABLE IF NOT EXISTS tool_errors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts BIGINT NOT NULL, agent_id TEXT NOT NULL, tool TEXT NOT NULL,
  code TEXT NOT NULL, task_id TEXT NOT NULL DEFAULT '', fingerprint TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS tool_errors_ts ON tool_errors(ts);`, "tool_errors")
}

var _ insights.Store = (*Store)(nil)

func (s *Store) InsertToolErrors(ctx context.Context, errs []insights.ToolError) error {
	return s.Atomic(ctx, func(st store.Tx) error {
		t := st.(*tx)
		for _, e := range errs {
			if _, err := t.q.ExecContext(t.ctx, `INSERT INTO tool_errors (ts, agent_id, tool, code, task_id, fingerprint)
				VALUES ($1, $2, $3, $4, $5, $6)`, e.TS.UnixMilli(), e.AgentID, e.Tool, e.Code, e.TaskID, e.Fingerprint); err != nil {
				return err
			}
		}
		return nil
	})
}

func (s *Store) ListToolErrors(ctx context.Context, since time.Time, limit int) ([]insights.ToolError, error) {
	rows, err := s.rdb.QueryContext(ctx, `SELECT id, ts, agent_id, tool, code, task_id, fingerprint FROM tool_errors
		WHERE ts >= $1 ORDER BY id ASC LIMIT $2`, since.UnixMilli(), limit)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var out []insights.ToolError
	for rows.Next() {
		var e insights.ToolError
		var ts int64
		if err := rows.Scan(&e.ID, &ts, &e.AgentID, &e.Tool, &e.Code, &e.TaskID, &e.Fingerprint); err != nil {
			return nil, err
		}
		e.TS = time.UnixMilli(ts).UTC()
		out = append(out, e)
	}
	return out, rows.Err()
}

func (s *Store) PruneToolErrors(ctx context.Context, before time.Time, keep int) error {
	return s.Atomic(ctx, func(st store.Tx) error {
		t := st.(*tx)
		_, err := t.q.ExecContext(t.ctx, `DELETE FROM tool_errors
			WHERE ts < $1 OR id <= (SELECT COALESCE(MAX(id), 0) FROM tool_errors) - $2`, before.UnixMilli(), keep)
		return err
	})
}
