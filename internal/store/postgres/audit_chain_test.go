package postgres_test

import (
	"testing"

	"github.com/SigmaUno/subspace/internal/audit"
	"github.com/SigmaUno/subspace/internal/model"
	"github.com/SigmaUno/subspace/internal/store"
)

func TestPGOpenChainsExistingAuditAndDetectsTampering(t *testing.T) {
	dsn, db := pgSchemaDSN(t)
	_, err := db.Exec(`CREATE TABLE audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts BIGINT NOT NULL, agent_id TEXT NOT NULL, role TEXT NOT NULL,
  tool TEXT NOT NULL, task_id TEXT NOT NULL DEFAULT '', before JSONB, after JSONB, note TEXT NOT NULL DEFAULT ''
);
CREATE FUNCTION audit_append_only() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'audit is append-only'; END $$;
CREATE TRIGGER audit_no_update BEFORE UPDATE ON audit FOR EACH ROW EXECUTE FUNCTION audit_append_only();
INSERT INTO audit(ts, agent_id, role, tool, task_id, before, after, note) VALUES
  (1000, 'owner', 'owner', 'approve_plan', '', NULL, '{"plan_id":"P-1","n":{"z":1.5,"a":"<x>"}}', ''),
  (2000, 'w-1', 'worker', 'claim_task', 'T-1', '{"status":"assigned"}', '{"status":"in_progress"}', 'go'),
  (3000, 'w-1', 'worker', 'submit', 'T-1', '{"status":"in_progress"}', '{"status":"submitted"}', '')`)
	if err != nil {
		t.Fatal(err)
	}

	s := openPGAt(t, dsn)
	verify := func() model.AuditCheck {
		var c model.AuditCheck
		read(t, s, func(tx store.Tx) (err error) { c, err = tx.VerifyAudit(); return })
		return c
	}
	if c := verify(); !c.OK || c.Events != 3 || c.Head.ID != 3 {
		t.Fatalf("migrated chain: %+v", c)
	}
	want, err := audit.Link("", audit.Record{ID: 1, TS: 1000, AgentID: "owner", Role: "owner", Tool: "approve_plan",
		After: `{"n":{"a":"<x>","z":1.5},"plan_id":"P-1"}`})
	if err != nil {
		t.Fatal(err)
	}
	var first model.AuditHead
	read(t, s, func(tx store.Tx) (err error) { first, err = tx.AuditHead(1); return })
	if first.Hash != want {
		t.Fatalf("first link %s, want %s", first.Hash, want)
	}

	write(t, s, func(tx store.Tx) error {
		return tx.InsertAudit(&model.AuditEvent{AgentID: "w-1", Role: "worker", Tool: "heartbeat", After: map[string]any{"pct": 40}})
	})
	if c := verify(); !c.OK || c.Events != 4 {
		t.Fatalf("after append: %+v", c)
	}

	if _, err := db.Exec(`UPDATE audit SET after = '{"status":"approved"}' WHERE id = 3`); err == nil {
		t.Fatal("update trigger missing after migration")
	}
	if _, err := db.Exec(`ALTER TABLE audit DISABLE TRIGGER audit_no_update; UPDATE audit SET after = '{"status":"approved"}' WHERE id = 3`); err != nil {
		t.Fatal(err)
	}
	if c := verify(); c.OK || c.BrokenID != 3 || c.Events != 2 {
		t.Fatalf("tampered: %+v", c)
	}
}
