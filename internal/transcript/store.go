const schema = `
CREATE TABLE IF NOT EXISTS task_transcripts (
  id INTEGER PRIMARY KEY AUTOINCREMENT, task_id TEXT NOT NULL, brief_id TEXT NOT NULL,
  first_offset INTEGER NOT NULL, last_offset INTEGER NOT NULL, line_count INTEGER NOT NULL,
  raw_bytes INTEGER NOT NULL, bytes INTEGER NOT NULL, sha256 TEXT NOT NULL, file TEXT NOT NULL,
  first_ts INTEGER NOT NULL, last_ts INTEGER NOT NULL, created_at INTEGER NOT NULL,
  UNIQUE(task_id, first_offset)
);
CREATE INDEX IF NOT EXISTS task_transcripts_brief ON task_transcripts(brief_id, created_at);
CREATE INDEX IF NOT EXISTS task_transcripts_created ON task_transcripts(created_at);
CREATE TABLE IF NOT EXISTS task_transcript_heads (task_id TEXT PRIMARY KEY, next_offset INTEGER NOT NULL);
`

const pgSchema = `
CREATE TABLE IF NOT EXISTS task_transcripts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id TEXT COLLATE "C" NOT NULL, brief_id TEXT COLLATE "C" NOT NULL,
  first_offset BIGINT NOT NULL, last_offset BIGINT NOT NULL, line_count BIGINT NOT NULL,
  raw_bytes BIGINT NOT NULL, bytes BIGINT NOT NULL, sha256 TEXT NOT NULL, file TEXT NOT NULL,
  first_ts BIGINT NOT NULL, last_ts BIGINT NOT NULL, created_at BIGINT NOT NULL,
  UNIQUE(task_id, first_offset)
);
CREATE INDEX IF NOT EXISTS task_transcripts_brief ON task_transcripts(brief_id, created_at);
CREATE INDEX IF NOT EXISTS task_transcripts_created ON task_transcripts(created_at);
CREATE TABLE IF NOT EXISTS task_transcript_heads (task_id TEXT COLLATE "C" PRIMARY KEY, next_offset BIGINT NOT NULL);
`

func init() {
	sqlite.RegisterSchema(schema)
	postgres.RegisterSchema(pgSchema, "task_transcripts", "task_transcript_heads")
}

const (
	insertCols  = `task_id, brief_id, first_offset, last_offset, line_count, raw_bytes, bytes, sha256, file, first_ts, last_ts, created_at`
	segmentCols = `id, ` + insertCols
)

type Segment struct {
	ID          int64     `json:"id"`
	TaskID      string    `json:"task_id"`
	BriefID     string    `json:"brief_id"`
	FirstOffset int64     `json:"first_offset"`
	LastOffset  int64     `json:"last_offset"`
	Lines       int       `json:"lines"`
	RawBytes    int64     `json:"raw_bytes"`
	Bytes       int64     `json:"bytes"`
	SHA256      string    `json:"sha256"`
	File        string    `json:"file"`
	FirstTS     time.Time `json:"first_ts"`
	LastTS      time.Time `json:"last_ts"`
	CreatedAt   time.Time `json:"created_at"`
}

func scanSegment(rows *sql.Rows) (Segment, error) {
	var (
		s                      Segment
		firstTS, lastTS, begun int64
	)
	if err := rows.Scan(&s.ID, &s.TaskID, &s.BriefID, &s.FirstOffset, &s.LastOffset, &s.Lines, &s.RawBytes, &s.Bytes,
		&s.SHA256, &s.File, &firstTS, &lastTS, &begun); err != nil {
		return Segment{}, err
	}
	s.FirstTS, s.LastTS, s.CreatedAt = time.UnixMilli(firstTS).UTC(), time.UnixMilli(lastTS).UTC(), time.UnixMilli(begun).UTC()
	return s, nil
}

func loadHead(ctx context.Context, st store.Store, task string) (int64, error) {
	return store.ViewSQL(ctx, st, func(q store.SQL) (int64, error) {
		return store.Scalar[int64](q, `SELECT next_offset FROM task_transcript_heads WHERE task_id = ?`, task)
	})
}

func insertSegment(ctx context.Context, st store.Store, seg *Segment) error {
	return st.Atomic(ctx, store.WithSQL(func(_ store.Tx, q store.SQL) error {
		if _, err := q.Exec(`INSERT INTO task_transcripts(`+insertCols+`) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)`,
			seg.TaskID, seg.BriefID, seg.FirstOffset, seg.LastOffset, seg.Lines, seg.RawBytes, seg.Bytes, seg.SHA256, seg.File,
			seg.FirstTS.UnixMilli(), seg.LastTS.UnixMilli(), seg.CreatedAt.UnixMilli()); err != nil {
			return err
		}
		id, err := store.Scalar[int64](q, `SELECT id FROM task_transcripts WHERE task_id = ? AND first_offset = ?`, seg.TaskID, seg.FirstOffset)
		if err != nil {
			return err
		}
		seg.ID = id
		_, err = q.Exec(`INSERT INTO task_transcript_heads(task_id, next_offset) VALUES(?, ?)
			ON CONFLICT(task_id) DO UPDATE SET next_offset = excluded.next_offset`, seg.TaskID, seg.LastOffset+1)
		return err
	}))
}

func taskSegments(ctx context.Context, st store.Store, task string, after int64) ([]Segment, error) {
	return store.ViewSQL(ctx, st, func(q store.SQL) ([]Segment, error) {
		return store.QueryAll(q, scanSegment, `SELECT `+segmentCols+` FROM task_transcripts WHERE task_id = ? AND last_offset > ? ORDER BY first_offset`, task, after)
	})
}

func briefSegments(ctx context.Context, st store.Store, brief string) ([]Segment, error) {
	return store.ViewSQL(ctx, st, func(q store.SQL) ([]Segment, error) {
		return store.QueryAll(q, scanSegment, `SELECT `+segmentCols+` FROM task_transcripts WHERE brief_id = ? ORDER BY created_at, id`, brief)
	})
}

func deleteSegments(ctx context.Context, st store.Store, segs []Segment, reason string, at time.Time) error {
	return st.Atomic(ctx, store.WithSQL(func(t store.Tx, q store.SQL) error {
		for _, s := range segs {
			if _, err := q.Exec(`DELETE FROM task_transcripts WHERE id = ?`, s.ID); err != nil {
				return err
			}
			task := s.TaskID
			if err := t.InsertAudit(&model.AuditEvent{TS: at, AgentID: "system", Role: "system", Tool: "transcript_prune", TaskID: &task,
				Before: map[string]any{"segment": s.ID, "first_offset": s.FirstOffset, "last_offset": s.LastOffset, "lines": s.Lines,
					"bytes": s.Bytes, "sha256": s.SHA256},
				After: map[string]any{"reason": reason}}); err != nil {
				return err
			}
		}
		return nil
	}))
}

type Stats struct {
	Segments    int       `json:"segments"`
	Lines       int64     `json:"lines"`
	Bytes       int64     `json:"bytes"`
	FirstOffset int64     `json:"first_offset"`
	LastOffset  int64     `json:"last_offset"`
	FirstTS     time.Time `json:"first_ts"`
	LastTS      time.Time `json:"last_ts"`
}

func taskStats(ctx context.Context, st store.Store, task string) (Stats, error) {
	var s Stats
	err := st.View(ctx, store.WithSQL(func(_ store.Tx, q store.SQL) error {
		rows, err := q.Query(`SELECT COUNT(*), COALESCE(SUM(line_count), 0), COALESCE(SUM(bytes), 0), COALESCE(MIN(first_offset), 0),
			COALESCE(MAX(last_offset), 0), COALESCE(MIN(first_ts), 0), COALESCE(MAX(last_ts), 0) FROM task_transcripts WHERE task_id = ?`, task)
		if err != nil {
			return err
		}
		defer func() { _ = rows.Close() }()
		var first, last int64
		if rows.Next() {
			if err := rows.Scan(&s.Segments, &s.Lines, &s.Bytes, &s.FirstOffset, &s.LastOffset, &first, &last); err != nil {
				return err
			}
		}
		if s.Segments > 0 {
			s.FirstTS, s.LastTS = time.UnixMilli(first).UTC(), time.UnixMilli(last).UTC()
		}
		return rows.Err()
	}))
	return s, err
}
