package postgres

const schema = `
CREATE TABLE IF NOT EXISTS seq (name TEXT COLLATE "C" PRIMARY KEY, n BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS kv (k TEXT COLLATE "C" PRIMARY KEY, v TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS briefs (
  id TEXT COLLATE "C" PRIMARY KEY, title TEXT NOT NULL, body TEXT NOT NULL, repos JSONB NOT NULL, status TEXT NOT NULL,
  max_cost_eur DOUBLE PRECISION NOT NULL, max_parallel INTEGER NOT NULL, allowed_providers JSONB NOT NULL,
  plan_status TEXT NOT NULL, created_at BIGINT NOT NULL, cross_review BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS briefs_status ON briefs(status, created_at);

CREATE TABLE IF NOT EXISTS plans (
  id TEXT COLLATE "C" PRIMARY KEY, brief_id TEXT COLLATE "C" NOT NULL, status TEXT NOT NULL, proposed_by TEXT NOT NULL,
  note TEXT, created_at BIGINT NOT NULL, decided_at BIGINT NOT NULL DEFAULT 0,
  warnings JSONB NOT NULL DEFAULT '[]'
);
CREATE INDEX IF NOT EXISTS plans_brief ON plans(brief_id, status);

CREATE TABLE IF NOT EXISTS tasks (
  id TEXT COLLATE "C" PRIMARY KEY, brief_id TEXT COLLATE "C" NOT NULL, plan_id TEXT COLLATE "C" NOT NULL,
  title TEXT NOT NULL, spec TEXT NOT NULL, acceptance JSONB NOT NULL, repo TEXT NOT NULL, branch TEXT NOT NULL,
  role TEXT NOT NULL, assignee TEXT COLLATE "C" NOT NULL DEFAULT '', reviewer TEXT COLLATE "C" NOT NULL DEFAULT '',
  depends_on JSONB NOT NULL, status TEXT NOT NULL, progress_pct INTEGER NOT NULL DEFAULT 0,
  last_heartbeat_at BIGINT NOT NULL DEFAULT 0, lease_expires_at BIGINT NOT NULL DEFAULT 0, claimed_at BIGINT NOT NULL DEFAULT 0,
  pr_url TEXT NOT NULL DEFAULT '', max_minutes INTEGER NOT NULL DEFAULT 0, max_cost_eur DOUBLE PRECISION NOT NULL DEFAULT 0,
  cost_used DOUBLE PRECISION NOT NULL DEFAULT 0, minutes_used INTEGER NOT NULL DEFAULT 0, review_rounds INTEGER NOT NULL DEFAULT 0,
  tests_passed INTEGER NOT NULL DEFAULT -1, tests_failed INTEGER NOT NULL DEFAULT 0, tests_at BIGINT NOT NULL DEFAULT 0,
  blocked_reason TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS tasks_brief ON tasks(brief_id, status);
CREATE INDEX IF NOT EXISTS tasks_assignee ON tasks(assignee, status);
CREATE INDEX IF NOT EXISTS tasks_reviewer ON tasks(reviewer, status);
CREATE INDEX IF NOT EXISTS tasks_status ON tasks(status);
CREATE INDEX IF NOT EXISTS tasks_plan ON tasks(plan_id);

CREATE TABLE IF NOT EXISTS agents (
  id TEXT COLLATE "C" PRIMARY KEY, role TEXT NOT NULL, kind TEXT NOT NULL, model TEXT NOT NULL, provider TEXT NOT NULL,
  status TEXT NOT NULL, pause_reason TEXT NOT NULL DEFAULT '', token_hash TEXT NOT NULL,
  last_seen_at BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL, spawned BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS agents_token ON agents(token_hash);
CREATE INDEX IF NOT EXISTS agents_role ON agents(role, status);

CREATE TABLE IF NOT EXISTS messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, thread_kind TEXT NOT NULL, thread_id TEXT COLLATE "C" NOT NULL,
  author_id TEXT NOT NULL, author_role TEXT NOT NULL, kind TEXT NOT NULL, body TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS messages_thread ON messages(thread_kind, thread_id, id);

CREATE TABLE IF NOT EXISTS questions (
  id TEXT COLLATE "C" PRIMARY KEY, brief_id TEXT NOT NULL DEFAULT '', task_id TEXT NOT NULL DEFAULT '', agent_id TEXT NOT NULL,
  question TEXT NOT NULL, options JSONB NOT NULL, status TEXT NOT NULL, answer TEXT NOT NULL DEFAULT '',
  answered_at BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS questions_status ON questions(status, created_at);

CREATE TABLE IF NOT EXISTS audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts BIGINT NOT NULL, agent_id TEXT NOT NULL, role TEXT NOT NULL,
  tool TEXT NOT NULL, task_id TEXT NOT NULL DEFAULT '', before JSONB, after JSONB, note TEXT NOT NULL DEFAULT '',
  hash TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS audit_agent ON audit(agent_id, id);
CREATE INDEX IF NOT EXISTS audit_task ON audit(task_id, id);

CREATE TABLE IF NOT EXISTS spawns (
  id TEXT COLLATE "C" PRIMARY KEY, brief_id TEXT COLLATE "C" NOT NULL, agent_id TEXT NOT NULL, kind TEXT NOT NULL,
  model TEXT NOT NULL, provider TEXT NOT NULL, status TEXT NOT NULL, spawner TEXT NOT NULL, error TEXT NOT NULL DEFAULT '',
  requested_by TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS spawns_brief ON spawns(brief_id);

CREATE TABLE IF NOT EXISTS usage_records (
  key TEXT COLLATE "C" PRIMARY KEY, ts BIGINT NOT NULL, agent_id TEXT NOT NULL DEFAULT '', task_id TEXT NOT NULL DEFAULT '',
  brief_id TEXT NOT NULL DEFAULT '', tokens_in BIGINT NOT NULL DEFAULT 0, tokens_out BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS usage_records_ts ON usage_records(ts);
CREATE INDEX IF NOT EXISTS audit_ts ON audit(ts);
CREATE INDEX IF NOT EXISTS tasks_created ON tasks(created_at);

CREATE OR REPLACE FUNCTION audit_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit is append-only';
END
$$;
CREATE OR REPLACE TRIGGER audit_no_update BEFORE UPDATE ON audit FOR EACH ROW EXECUTE FUNCTION audit_append_only();
CREATE OR REPLACE TRIGGER audit_no_delete BEFORE DELETE ON audit FOR EACH ROW EXECUTE FUNCTION audit_append_only();
CREATE OR REPLACE TRIGGER audit_no_truncate BEFORE TRUNCATE ON audit FOR EACH STATEMENT EXECUTE FUNCTION audit_append_only();
`
