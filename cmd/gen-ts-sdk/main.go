const header = "// Code generated by cmd/gen-ts-sdk; DO NOT EDIT.\n"

func main() {
	out := flag.String("o", "sdk/ts/src/generated", "output directory")
	flag.Parse()
	files, err := build()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-ts-sdk:", err)
		os.Exit(1)
	}
	if err := os.MkdirAll(*out, 0o755); err != nil { //nolint:gosec // source directory checked into the repo
		fmt.Fprintln(os.Stderr, "gen-ts-sdk:", err)
		os.Exit(1)
	}
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(*out, name), src, 0o644); err != nil { //nolint:gosec // source file checked into the repo
			fmt.Fprintln(os.Stderr, "gen-ts-sdk:", err)
			os.Exit(1)
		}
	}
}

func build() (map[string][]byte, error) {
	raw, err := openapi.Build(openapi.Options{Version: "sdk"})
	if err != nil {
		return nil, err
	}
	return generate(raw)
}

type typeSet []string

func (t *typeSet) UnmarshalJSON(b []byte) error {
	var one string
	if err := json.Unmarshal(b, &one); err == nil {
		*t = typeSet{one}
		return nil
	}
	var many []string
	if err := json.Unmarshal(b, &many); err != nil {
		return err
	}
	*t = many
	return nil
}

type schema struct {
	Ref                  string             `json:"$ref"`
	Type                 typeSet            `json:"type"`
	Format               string             `json:"format"`
	Properties           map[string]*schema `json:"properties"`
	Required             []string           `json:"required"`
	Items                *schema            `json:"items"`
	AdditionalProperties *schema            `json:"additionalProperties"`
	OneOf                []*schema          `json:"oneOf"`
}

type media struct {
	Schema *schema `json:"schema"`
}

type content struct {
	Content map[string]media `json:"content"`
}

type parameter struct {
	Name     string  `json:"name"`
	In       string  `json:"in"`
	Required bool    `json:"required"`
	Schema   *schema `json:"schema"`
}

type operation struct {
	ID          string             `json:"operationId"`
	Parameters  []parameter        `json:"parameters"`
	RequestBody *content           `json:"requestBody"`
	Responses   map[string]content `json:"responses"`
}

type document struct {
	Paths      map[string]map[string]operation `json:"paths"`
	Components struct {
		Schemas map[string]*schema `json:"schemas"`
	} `json:"components"`
}

type generator struct {
	schemas   map[string]*schema
	inputOnly map[string]bool
	prefix    string
}

var (
	identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
	reserved   = []string{"Array", "Partial", "Promise", "Record", "Uint8Array", "FormData", "URLSearchParams"}
)

func generate(raw []byte) (map[string][]byte, error) {
	var doc document
	if err := json.Unmarshal(raw, &doc); err != nil {
		return nil, err
	}
	g := &generator{schemas: doc.Components.Schemas}
	g.inputOnly = g.classify(doc.Paths)
	types, err := g.types()
	if err != nil {
		return nil, err
	}
	g.prefix = "T."
	ops, err := g.operations(doc.Paths)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{"types.ts": types, "operations.ts": ops}, nil
}

func (g *generator) classify(paths map[string]map[string]operation) map[string]bool {
	in, out := map[string]bool{}, map[string]bool{}
	for _, methods := range paths {
		for _, op := range methods {
			if op.RequestBody != nil {
				if m, ok := op.RequestBody.Content["application/json"]; ok {
					g.reach(m.Schema, in)
				}
			}
			for _, r := range op.Responses {
				for _, m := range r.Content {
					g.reach(m.Schema, out)
				}
			}
		}
	}
	only := map[string]bool{}
	for n := range in {
		if !out[n] {
			only[n] = true
		}
	}
	return only
}

func (g *generator) reach(s *schema, seen map[string]bool) {
	if s == nil {
		return
	}
	if s.Ref != "" {
		name := s.Ref[strings.LastIndex(s.Ref, "/")+1:]
		if seen[name] {
			return
		}
		seen[name] = true
		g.reach(g.schemas[name], seen)
		return
	}
	g.reach(s.Items, seen)
	g.reach(s.AdditionalProperties, seen)
	for _, o := range s.OneOf {
		g.reach(o, seen)
	}
	for _, p := range s.Properties {
		g.reach(p, seen)
	}
}

func (g *generator) types() ([]byte, error) {
	names := make([]string, 0, len(g.schemas))
	for n := range g.schemas {
		if !identifier.MatchString(n) || slices.Contains(reserved, n) {
			return nil, fmt.Errorf("schema name %q is not usable as a type name", n)
		}
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString(header)
	for _, n := range names {
		s := g.schemas[n]
		b.WriteString("\n")
		if s.Ref == "" && len(s.OneOf) == 0 && s.isObject() && len(s.Properties) > 0 {
			fmt.Fprintf(&b, "export interface %s {\n", n)
			for _, f := range g.fields(s, g.inputOnly[n]) {
				fmt.Fprintf(&b, "  %s;\n", f)
			}
			b.WriteString("}\n")
			continue
		}
		fmt.Fprintf(&b, "export type %s = %s;\n", n, g.ts(s))
	}
	return b.Bytes(), nil
}

func (s *schema) isObject() bool {
	return slices.Contains(s.Type, "object")
}

func (s *schema) nullable() bool {
	return slices.Contains(s.Type, "null")
}

func (g *generator) fields(s *schema, lenient bool) []string {
	keys := make([]string, 0, len(s.Properties))
	for k := range s.Properties {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	out := make([]string, 0, len(keys))
	for _, k := range keys {
		p := s.Properties[k]
		name := k
		if !identifier.MatchString(k) {
			name = fmt.Sprintf("%q", k)
		}
		mark := "?"
		if slices.Contains(s.Required, k) && !p.unknown() && (!lenient || !g.nullable(p)) {
			mark = ""
		}
		out = append(out, fmt.Sprintf("%s%s: %s", name, mark, g.ts(p)))
	}
	return out
}

func (g *generator) nullable(s *schema) bool {
	if s.nullable() {
		return true
	}
	for _, o := range s.OneOf {
		if o.nullable() {
			return true
		}
	}
	return false
}

func (s *schema) unknown() bool {
	return s.Ref == "" && len(s.OneOf) == 0 && len(s.Type) == 0 && len(s.Properties) == 0
}

func (g *generator) ts(s *schema) string {
	if s == nil || s.unknown() {
		return "unknown"
	}
	if s.Ref != "" {
		return g.prefix + s.Ref[strings.LastIndex(s.Ref, "/")+1:]
	}
	if len(s.OneOf) > 0 {
		parts := make([]string, len(s.OneOf))
		for i, o := range s.OneOf {
			if len(o.Type) == 1 && o.Type[0] == "null" {
				parts[i] = "null"
				continue
			}
			parts[i] = g.ts(o)
		}
		return strings.Join(parts, " | ")
	}
	var base string
	for _, t := range s.Type {
		if t == "null" {
			continue
		}
		base = g.base(t, s)
	}
	if s.nullable() {
		if base == "" {
			return "null"
		}
		return base + " | null"
	}
	return base
}

func (g *generator) base(t string, s *schema) string {
	switch t {
	case "string":
		if s.Format == "binary" {
			return "Uint8Array"
		}
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		inner := g.ts(s.Items)
		if strings.ContainsAny(inner, " |") {
			inner = "(" + inner + ")"
		}
		return inner + "[]"
	case "object":
		switch {
		case len(s.Properties) > 0:
			return "{ " + strings.Join(g.fields(s, false), "; ") + " }"
		case s.AdditionalProperties != nil:
			return "Record<string, " + g.ts(s.AdditionalProperties) + ">"
		}
		return "Record<string, unknown>"
	}
	return "unknown"
}

type bodyKind struct {
	ts       string
	required bool
	mime     string
}

func (g *generator) body(rb *content) (bodyKind, bool) {
	if rb == nil {
		return bodyKind{}, false
	}
	if m, ok := rb.Content["application/json"]; ok {
		return bodyKind{ts: g.ts(m.Schema), required: g.mustSend(m.Schema)}, true
	}
	types := map[string]string{
		"multipart/form-data":               "FormData",
		"application/x-www-form-urlencoded": "URLSearchParams",
		"text/markdown":                     "string",
		"text/plain":                        "string",
	}
	mimes := make([]string, 0, len(rb.Content))
	for k := range rb.Content {
		mimes = append(mimes, k)
	}
	sort.Strings(mimes)
	for _, k := range mimes {
		if t, ok := types[k]; ok {
			return bodyKind{ts: t, required: true, mime: k}, true
		}
	}
	return bodyKind{ts: "NonNullable<RequestInit[\"body\"]>", required: true, mime: mimes[0]}, true
}

func (g *generator) mustSend(s *schema) bool {
	if s == nil || s.unknown() {
		return false
	}
	if s.Ref != "" {
		target, ok := g.schemas[s.Ref[strings.LastIndex(s.Ref, "/")+1:]]
		if !ok {
			return true
		}
		return g.mustSend(target)
	}
	if s.isObject() {
		return len(s.Required) > 0
	}
	return true
}

func (g *generator) response(op operation) (kind, ts string, ok bool, err error) {
	codes := make([]string, 0, len(op.Responses))
	for c := range op.Responses {
		if c != "default" {
			codes = append(codes, c)
		}
	}
	sort.Strings(codes)
	if len(codes) == 0 {
		return "", "", false, fmt.Errorf("%s has no success response", op.ID)
	}
	code := codes[0]
	if code == fmt.Sprint(http.StatusNoContent) || len(op.Responses[code].Content) == 0 {
		return "none", "void", true, nil
	}
	cs := op.Responses[code].Content
	if m, found := cs["application/json"]; found {
		return "json", g.ts(m.Schema), true, nil
	}
	for mime := range cs {
		switch mime {
		case "text/event-stream":
			return "", "", false, nil
		case "application/octet-stream":
			return "bytes", "Uint8Array", true, nil
		}
	}
	return "text", "string", true, nil
}

func (g *generator) operations(paths map[string]map[string]operation) ([]byte, error) {
	type entry struct {
		method, path string
		op           operation
	}
	var entries []entry
	for p, methods := range paths {
		if !strings.HasPrefix(p, "/api/v1/") && p != "/healthz" {
			continue
		}
		for m, op := range methods {
			entries = append(entries, entry{strings.ToUpper(m), p, op})
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].op.ID < entries[j].op.ID })
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("import type { Requester } from \"../transport.ts\";\nimport type * as T from \"./types.ts\";\n")
	seen := map[string]bool{}
	for _, e := range entries {
		if seen[e.op.ID] {
			return nil, fmt.Errorf("duplicate operation id %s", e.op.ID)
		}
		seen[e.op.ID] = true
		kind, resp, ok, err := g.response(e.op)
		if err != nil {
			return nil, err
		}
		if !ok {
			continue
		}
		skip := false
		for _, p := range e.op.Parameters {
			if p.In == "header" {
				skip = true
			}
		}
		if skip {
			continue
		}
		decl, err := g.function(e.method, e.path, e.op, kind, resp)
		if err != nil {
			return nil, err
		}
		b.WriteString("\n")
		b.WriteString(decl)
	}
	return b.Bytes(), nil
}

func (g *generator) function(method, path string, op operation, kind, resp string) (string, error) {
	var pathFields, queryFields []string
	queryRequired := false
	for _, p := range op.Parameters {
		if !identifier.MatchString(p.Name) {
			return "", fmt.Errorf("%s: parameter %q is not an identifier", op.ID, p.Name)
		}
		switch p.In {
		case "path":
			pathFields = append(pathFields, p.Name+": "+g.ts(p.Schema))
		case "query":
			mark := "?"
			if p.Required {
				mark = ""
				queryRequired = true
			}
			queryFields = append(queryFields, p.Name+mark+": "+g.ts(p.Schema))
		}
	}
	var parts []string
	required := false
	if len(pathFields) > 0 {
		parts = append(parts, "path: { "+strings.Join(pathFields, "; ")+" }")
		required = true
	}
	if len(queryFields) > 0 {
		mark := "?"
		if queryRequired {
			mark = ""
			required = true
		}
		parts = append(parts, "query"+mark+": { "+strings.Join(queryFields, "; ")+" }")
	}
	body, hasBody := g.body(op.RequestBody)
	if hasBody {
		mark := "?"
		if body.required {
			mark = ""
			required = true
		}
		parts = append(parts, "body"+mark+": "+body.ts)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "export function %s(\n  r: Requester,\n", op.ID)
	if len(parts) > 0 {
		mark := "?"
		if required {
			mark = ""
		}
		fmt.Fprintf(&b, "  args%s: { %s },\n", mark, strings.Join(parts, "; "))
	}
	fmt.Fprintf(&b, "): Promise<%s> {\n", resp)
	extra := fmt.Sprintf("response: %q", kind)
	if body.mime != "" {
		extra = fmt.Sprintf("contentType: %q, %s", body.mime, extra)
	}
	spread := ""
	if len(parts) > 0 {
		spread = "...args, "
	}
	fmt.Fprintf(&b, "  return r.request(%q, %q, { %s%s });\n}\n", method, path, spread, extra)
	return b.String(), nil
}
