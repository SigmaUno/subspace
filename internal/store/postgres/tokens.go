package postgres

import (
	"context"
	"database/sql"
	"errors"
	"strconv"
	"strings"
	"time"

	"github.com/SigmaUno/subspace/internal/store"
	"github.com/SigmaUno/subspace/internal/tokens"
)

func init() {
	RegisterSchema(`
CREATE TABLE IF NOT EXISTS api_tokens (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, hash TEXT NOT NULL UNIQUE, scope TEXT NOT NULL,
  created_at BIGINT NOT NULL, last_used_at BIGINT, revoked_at BIGINT, expires_at BIGINT
);`, "api_tokens")
}

const apiAccessCols = `seq, name, scope, created_at, last_used_at, revoked_at, expires_at`

var _ tokens.Store = (*Store)(nil)

func apiTokenSeq(id string) (int64, bool) {
	n, err := strconv.ParseInt(strings.TrimPrefix(id, "K-"), 10, 64)
	return n, err == nil && strings.HasPrefix(id, "K-") && n > 0
}

func msOrNil(t *time.Time) any {
	if t == nil {
		return nil
	}
	return t.UnixMilli()
}

func timeOrNil(ms sql.NullInt64) *time.Time {
	if !ms.Valid {
		return nil
	}
	t := time.UnixMilli(ms.Int64).UTC()
	return &t
}

func scanAPIToken(row scanner) (*tokens.Token, error) {
	var (
		t                    tokens.Token
		seq, created         int64
		used, revoked, until sql.NullInt64
	)
	if err := row.Scan(&seq, &t.Name, &t.Scope, &created, &used, &revoked, &until); err != nil {
		return nil, err
	}
	t.ID = "K-" + strconv.FormatInt(seq, 10)
	t.CreatedAt = time.UnixMilli(created).UTC()
	t.LastUsedAt, t.RevokedAt, t.ExpiresAt = timeOrNil(used), timeOrNil(revoked), timeOrNil(until)
	return &t, nil
}

func (s *Store) CreateAPIToken(ctx context.Context, t *tokens.Token, hash string, audit tokens.AuditFunc) error {
	return s.Atomic(ctx, func(st store.Tx) error {
		var seq int64
		tt := st.(*tx)
		err := tt.q.QueryRowContext(tt.ctx,
			`INSERT INTO api_tokens (name, hash, scope, created_at, expires_at) VALUES ($1, $2, $3, $4, $5) RETURNING seq`,
			t.Name, hash, t.Scope, t.CreatedAt.UnixMilli(), msOrNil(t.ExpiresAt)).Scan(&seq)
		if err != nil {
			return mapErr(err)
		}
		t.ID = "K-" + strconv.FormatInt(seq, 10)
		return st.InsertAudit(audit(t))
	})
}

func (s *Store) ListAPITokens(ctx context.Context) ([]*tokens.Token, error) {
	rows, err := s.rdb.QueryContext(ctx, `SELECT `+apiAccessCols+` FROM api_tokens ORDER BY seq`)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var out []*tokens.Token
	for rows.Next() {
		t, err := scanAPIToken(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

func (s *Store) APITokenByHash(ctx context.Context, hash string) (*tokens.Token, error) {
	t, err := scanAPIToken(s.rdb.QueryRowContext(ctx, `SELECT `+apiAccessCols+` FROM api_tokens WHERE hash = $1`, hash))
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	return t, err
}

func (s *Store) RevokeAPIToken(ctx context.Context, id string, at time.Time, audit tokens.AuditFunc) (*tokens.Token, error) {
	seq, ok := apiTokenSeq(id)
	if !ok {
		return nil, store.ErrNotFound
	}
	var out *tokens.Token
	err := s.Atomic(ctx, func(st store.Tx) error {
		t := st.(*tx)
		cur, err := scanAPIToken(t.q.QueryRowContext(t.ctx, `SELECT `+apiAccessCols+` FROM api_tokens WHERE seq = $1`, seq))
		if errors.Is(err, sql.ErrNoRows) {
			return store.ErrNotFound
		}
		if err != nil {
			return err
		}
		if cur.RevokedAt != nil {
			return tokens.ErrRevoked
		}
		if err := t.exec(`UPDATE api_tokens SET revoked_at = $1 WHERE seq = $2`, at.UnixMilli(), seq); err != nil {
			return err
		}
		cur.RevokedAt = &at
		out = cur
		return st.InsertAudit(audit(cur))
	})
	return out, err
}

func (s *Store) TouchAPIToken(ctx context.Context, id string, at time.Time) error {
	seq, ok := apiTokenSeq(id)
	if !ok {
		return store.ErrNotFound
	}
	return s.Atomic(ctx, func(st store.Tx) error {
		return st.(*tx).exec(`UPDATE api_tokens SET last_used_at = $1 WHERE seq = $2 AND (last_used_at IS NULL OR last_used_at < $1)`,
			at.UnixMilli(), seq)
	})
}
