package postgres

import (
	"database/sql"
	"errors"

	"github.com/SigmaUno/subspace/internal/model"
)

const retentionSchema = `
CREATE TABLE IF NOT EXISTS retention_segments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT COLLATE "C" NOT NULL, seq BIGINT NOT NULL, file TEXT NOT NULL,
  row_count BIGINT NOT NULL, bytes BIGINT NOT NULL, sha256 TEXT NOT NULL, cutoff BIGINT NOT NULL,
  first_id BIGINT NOT NULL DEFAULT 0, last_id BIGINT NOT NULL DEFAULT 0,
  prev_hash TEXT NOT NULL DEFAULT '', last_hash TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
  UNIQUE (kind, seq)
);
CREATE INDEX IF NOT EXISTS retention_segments_anchor ON retention_segments(kind, status, last_id);
CREATE OR REPLACE FUNCTION retention_segments_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'retention manifest is append-only';
  END IF;
  IF (NEW.id, NEW.kind, NEW.seq, NEW.file, NEW.row_count, NEW.bytes, NEW.sha256, NEW.cutoff, NEW.first_id, NEW.last_id,
      NEW.prev_hash, NEW.last_hash, NEW.created_at)
     IS DISTINCT FROM (OLD.id, OLD.kind, OLD.seq, OLD.file, OLD.row_count, OLD.bytes, OLD.sha256, OLD.cutoff, OLD.first_id,
      OLD.last_id, OLD.prev_hash, OLD.last_hash, OLD.created_at)
     OR NOT ((OLD.status = 'pending' AND NEW.status IN ('pending', 'archived', 'restored'))
       OR (OLD.status = 'archived' AND NEW.status IN ('archived', 'restored'))
       OR (OLD.status = 'restored' AND NEW.status = 'restored')) THEN
    RAISE EXCEPTION 'retention manifest is immutable';
  END IF;
  RETURN NEW;
END
$$;
CREATE OR REPLACE TRIGGER retention_segments_guard BEFORE UPDATE OR DELETE ON retention_segments
  FOR EACH ROW EXECUTE FUNCTION retention_segments_guard();
CREATE OR REPLACE FUNCTION audit_delete_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM retention_segments s WHERE s.kind = 'audit' AND s.status IN ('pending', 'archived')
      AND OLD.id BETWEEN s.first_id AND s.last_id) THEN
    RAISE EXCEPTION 'audit is append-only';
  END IF;
  RETURN OLD;
END
$$;
CREATE OR REPLACE TRIGGER audit_no_delete BEFORE DELETE ON audit FOR EACH ROW EXECUTE FUNCTION audit_delete_guard();
`

func init() { RegisterSchema(retentionSchema, "retention_segments") }

func (t *tx) auditAnchor() (model.AuditHead, error) {
	var h model.AuditHead
	err := t.q.QueryRowContext(t.ctx, `SELECT last_id, last_hash FROM retention_segments
		WHERE kind = 'audit' AND status IN ('pending', 'archived') ORDER BY last_id DESC LIMIT 1`).Scan(&h.ID, &h.Hash)
	if errors.Is(err, sql.ErrNoRows) {
		return model.AuditHead{}, nil
	}
	return h, err
}
