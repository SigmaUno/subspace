package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"
	"time"
)

const header = "// Code generated by cmd/gen-ts; DO NOT EDIT.\n"

func main() {
	out := flag.String("o", "web/lib/generated-types.ts", "output file")
	flag.Parse()
	src, err := generate(registry)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-ts:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil { //nolint:gosec // source file checked into the repo
		fmt.Fprintln(os.Stderr, "gen-ts:", err)
		os.Exit(1)
	}
}

type entry struct {
	name  string
	value any
}

type generator struct {
	names map[reflect.Type]string
	todo  []reflect.Type
}

func generate(entries []entry) ([]byte, error) {
	g := &generator{names: make(map[reflect.Type]string, len(entries))}
	for _, e := range entries {
		t := reflect.TypeOf(e.value)
		if t.Kind() != reflect.Struct {
			return nil, fmt.Errorf("%s is not a struct", e.name)
		}
		for _, n := range g.names {
			if n == e.name {
				return nil, fmt.Errorf("duplicate type name %s", e.name)
			}
		}
		if prev, ok := g.names[t]; ok {
			return nil, fmt.Errorf("%s registered as both %s and %s", t, prev, e.name)
		}
		g.names[t] = e.name
		g.todo = append(g.todo, t)
	}
	decls := make(map[string]string, len(entries))
	for _, t := range g.todo {
		body, err := g.declare(t)
		if err != nil {
			return nil, err
		}
		decls[g.names[t]] = body
	}
	names := make([]string, 0, len(decls))
	for n := range decls {
		names = append(names, n)
	}
	sort.Strings(names)
	var buf bytes.Buffer
	buf.WriteString(header)
	for _, n := range names {
		buf.WriteString("\n")
		buf.WriteString(decls[n])
	}
	return buf.Bytes(), nil
}

type field struct {
	name     string
	typ      reflect.Type
	optional bool
	depth    int
}

func (g *generator) declare(t reflect.Type) (string, error) {
	fields, err := collect(t, 0)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", g.names[t])
	for _, f := range fields {
		ts, err := g.tsType(f.typ)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", g.names[t], f.name, err)
		}
		mark := ""
		if f.optional {
			mark = "?"
			ts = strings.TrimSuffix(ts, " | null")
		}
		fmt.Fprintf(&b, "  %s%s: %s;\n", f.name, mark, ts)
	}
	b.WriteString("}\n")
	return b.String(), nil
}

func collect(t reflect.Type, depth int) ([]field, error) {
	var out []field
	for i := range t.NumField() {
		sf := t.Field(i)
		tag, hasTag := sf.Tag.Lookup("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if sf.Anonymous && name == "" {
			et := sf.Type
			if et.Kind() == reflect.Pointer {
				et = et.Elem()
			}
			if et.Kind() == reflect.Struct {
				inner, err := collect(et, depth+1)
				if err != nil {
					return nil, err
				}
				out = append(out, inner...)
				continue
			}
		}
		if !sf.IsExported() {
			continue
		}
		if !hasTag || name == "" {
			return nil, fmt.Errorf("%s.%s has no json name", t, sf.Name)
		}
		out = append(out, field{name: name, typ: sf.Type, optional: strings.Contains(","+opts+",", ",omitempty,"), depth: depth})
	}
	if depth > 0 {
		return out, nil
	}
	return dedupe(out), nil
}

func dedupe(fields []field) []field {
	best := make(map[string]int, len(fields))
	for i, f := range fields {
		if j, ok := best[f.name]; !ok || f.depth < fields[j].depth {
			best[f.name] = i
		}
	}
	out := make([]field, 0, len(best))
	for i, f := range fields {
		if best[f.name] == i {
			out = append(out, f)
		}
	}
	return out
}

var timeType = reflect.TypeFor[time.Time]()

func (g *generator) tsType(t reflect.Type) (string, error) {
	if t == timeType {
		return "string", nil
	}
	switch t.Kind() {
	case reflect.Pointer:
		inner, err := g.tsType(t.Elem())
		if err != nil {
			return "", err
		}
		if strings.HasSuffix(inner, " | null") {
			return inner, nil
		}
		return inner + " | null", nil
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 && t.Kind() == reflect.Slice {
			return "string | null", nil
		}
		inner, err := g.tsType(t.Elem())
		if err != nil {
			return "", err
		}
		return elem(inner) + "[] | null", nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map key %s is not a string", t.Key())
		}
		inner, err := g.tsType(t.Elem())
		if err != nil {
			return "", err
		}
		return "Record<string, " + inner + "> | null", nil
	case reflect.Struct:
		name, ok := g.names[t]
		if !ok {
			return "", fmt.Errorf("struct %s is not registered", t)
		}
		return name, nil
	}
	return "", fmt.Errorf("unsupported kind %s", t.Kind())
}

func elem(inner string) string {
	if strings.Contains(inner, " ") {
		return "(" + inner + ")"
	}
	return inner
}
